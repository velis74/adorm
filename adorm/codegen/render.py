__all__ = ["HEADER", "render_module", "render_package"]

HEADER = "# Generated by adorm generate: do not edit, run adorm generate again."
"""The first line of every generated file; a file starting with it belongs to the generator."""

INDENT = "    "

_STDLIB = frozenset({"datetime", "decimal", "typing", "uuid", "builtins", "enum", "ipaddress", "collections"})
_RELATION_CLASSES = {
    "foreign_key": "ForeignKey",
    "reverse_foreign_key": "ReverseForeignKey",
    "reverse_one_to_one": "ReverseOneToOne",
    "many_to_many": "ManyToMany",
    "generic_foreign_key": "GenericForeignKey",
    "tenant": "TenantRelation",
}


def _str_literal(value: str) -> str:
    # The quotes that need fewer escapes, double quotes on a tie, as ruff and black write strings.
    text = repr(value)
    if text[0] == '"' or value.count('"') > value.count("'"):
        return text
    return '"' + text[1:-1].replace("\\'", "'").replace('"', '\\"') + '"'


def can_render_value(value: Any) -> bool:
    """Whether `render_module()` can write ``value`` as a Python literal (a default or a ``Literal`` value)."""
    if value is None or isinstance(value, bool | int | str | bytes | decimal.Decimal | uuid.UUID | datetime.timedelta):
        return True
    if isinstance(value, float):
        return True
    if isinstance(value, datetime.datetime):
        return value.tzinfo is None or value.tzinfo is datetime.UTC
    if isinstance(value, datetime.date):
        return True
    if isinstance(value, datetime.time):
        return value.tzinfo is None
    if isinstance(value, list | tuple):
        return all(can_render_value(item) for item in value)
    if isinstance(value, dict):
        return all(isinstance(key, str) and can_render_value(item) for key, item in value.items())
    return False


class _Imports:
    """The imports of a module; names that clash with ``reserved`` names are imported under an alias."""

    def __init__(self, reserved: Iterable[str], line_length: int) -> None:
        self.reserved = set(reserved)
        self.line_length = line_length
        self.modules: dict[str, str] = {}
        self.names: dict[tuple[str, str], str] = {}

    def _local(self, name: str) -> str:
        taken = self.reserved | set(self.modules.values()) | set(self.names.values())
        while name in taken:
            name = f"_{name}"
        return name

    def module(self, module: str) -> str:
        if module not in self.modules:
            local = module if "." not in module else module.rpartition(".")[2]
            self.modules[module] = local if local == module and module not in self.reserved else self._local(local)
        return self.modules[module]

    def name(self, module: str, name: str) -> str:
        key = (module, name)
        if key not in self.names:
            self.names[key] = self._local(name)
        return self.names[key]

    def lines(self) -> list[str]:
        sections: dict[str, list[str]] = {"stdlib": [], "third_party": [], "local": []}
        plain = sorted(self.modules.items(), key=lambda item: item[0].lower())
        for module, local in plain:
            section = "stdlib" if module.partition(".")[0] in _STDLIB else "third_party"
            if local == module:
                sections[section].append(f"import {module}")
            elif "." in module and module.rpartition(".")[2] == local:
                sections[section].append(f"from {module.rpartition('.')[0]} import {local}")
            else:
                sections[section].append(f"import {module} as {local}")
        grouped: dict[str, list[tuple[str, str]]] = {}
        for (module, name), local in self.names.items():
            grouped.setdefault(module, []).append((name, local))
        for module in sorted(grouped, key=lambda m: (m.startswith("."), m.lstrip(".").lower())):
            names = sorted(grouped[module], key=lambda item: (not item[0][:1].isupper(), item[0].lower()))
            text = ", ".join(name if name == local else f"{name} as {local}" for name, local in names)
            if module.startswith("."):
                section = "local"
            elif module.partition(".")[0] in _STDLIB:
                section = "stdlib"
            else:
                section = "third_party"
            line = f"from {module} import {text}"
            if len(line) > self.line_length:
                items = "".join(f"{INDENT}{item.strip()},\n" for item in text.split(","))
                line = f"from {module} import (\n{items})"
            sections[section].append(line)
        return ["\n".join(lines) for lines in sections.values() if lines]


class _Text:
    """A keyword argument whose string value may be split over several lines."""

    def __init__(self, key: str, text: str) -> None:
        self.key = key
        self.text = text


class _Writer:
    def __init__(self, imports: _Imports, line_length: int) -> None:
        self.imports = imports
        self.line_length = line_length

    def value(self, value: Any) -> str:
        if isinstance(value, enum.Enum):
            value = value.value
        if value is None or isinstance(value, bool | int):
            return repr(value)
        if isinstance(value, float):
            return repr(value) if math.isfinite(value) else f'float("{value}")'
        if isinstance(value, str):
            return _str_literal(value)
        if isinstance(value, bytes):
            text = repr(value)
            if text[1] == "'" and '"' not in text:
                text = 'b"' + text[2:-1].replace("\\'", "'") + '"'
            return text
        if isinstance(value, decimal.Decimal):
            return f'{self.imports.module("decimal")}.Decimal("{value}")'
        if isinstance(value, uuid.UUID):
            return f'{self.imports.module("uuid")}.UUID("{value}")'
        if isinstance(value, datetime.datetime | datetime.date | datetime.time | datetime.timedelta):
            module = self.imports.module("datetime")
            if isinstance(value, datetime.datetime) and value.tzinfo is not None:
                text = repr(value.replace(tzinfo=None))[len("datetime.") : -1] + f", tzinfo={module}.UTC)"
            else:
                text = repr(value)[len("datetime.") :]
            return f"{module}.{text}"
        if isinstance(value, list):
            return "[" + ", ".join(self.value(item) for item in value) + "]"
        if isinstance(value, tuple):
            items = [self.value(item) for item in value]
            return "(" + ", ".join(items) + ("," if len(items) == 1 else "") + ")"
        if isinstance(value, dict):
            return "{" + ", ".join(f"{self.value(key)}: {self.value(item)}" for key, item in value.items()) + "}"
        raise ValueError(f"cannot write {value!r} as a Python literal")

    def ref(self, dotted: str) -> str:
        """A reference to the dotted name ``dotted``: a builtin, a ``typing`` name or a name in a module."""
        module, _, name = dotted.rpartition(".")
        if not module or module == "builtins":
            return name
        if module == "typing":
            return self.imports.name("typing", name)
        return f"{self.imports.module(module)}.{name}"

    def type(self, spec: TypeSpec, aliases: Mapping[TypeSpec, str] | None = None) -> str:
        bare = spec.with_nullable(False)
        if aliases and bare in aliases:
            text = aliases[bare]
        elif spec.values:
            text = f"{self.ref(spec.name)}[{', '.join(self.value(v) for v in spec.values)}]"
        else:
            text = self.ref(spec.name)
            if spec.args:
                text += f"[{', '.join(self.type(arg) for arg in spec.args)}]"
        return f"{text} | None" if spec.nullable and not spec.is_any else text

    def call(self, head: str, callee: str, args: Sequence[str | _Text], indent: str, tail: str = "") -> list[str]:
        """``head + callee(args) + tail`` on one line, or with one argument per line when it does not fit."""
        flat = [arg if isinstance(arg, str) else f"{arg.key}={self.value(arg.text)}" for arg in args]
        line = f"{indent}{head}{callee}({', '.join(flat)}){tail}"
        if len(line) <= self.line_length or not args:
            return [line]
        inner = indent + INDENT
        lines = [f"{indent}{head}{callee}("]
        for arg, text in zip(args, flat, strict=True):
            if len(f"{inner}{text},") <= self.line_length:
                lines.append(f"{inner}{text},")
            elif isinstance(arg, _Text):
                lines.append(f"{inner}{arg.key}=(")
                lines.extend(f"{inner}{INDENT}{chunk}" for chunk in self._chunks(arg.text, len(inner) + len(INDENT)))
                lines.append(f"{inner}),")
            else:
                lines.extend(self._explode_argument(text, inner))
        lines.append(f"{indent}){tail}")
        return lines

    def _chunks(self, text: str, indent: int) -> list[str]:
        """``text`` as string literals that fit the line from column ``indent``, split after spaces."""
        words = text.split(" ")
        chunks: list[str] = []
        current = ""
        for index, word in enumerate(words):
            piece = word if index == len(words) - 1 else f"{word} "
            if current and indent + len(self.value(current + piece)) > self.line_length:
                chunks.append(current)
                current = piece
            else:
                current += piece
        chunks.append(current)
        return [self.value(chunk) for chunk in chunks]

    def _explode_argument(self, arg: str, indent: str) -> list[str]:
        # A keyword argument whose value is a dict, list or tuple literal is exploded one item per line.
        key, sep, value = arg.partition("=")
        if sep and value[:1] and value[-1:] == _CLOSING.get(value[:1]):
            items = _split_top_level(value[1:-1])
            if items:
                lines = [f"{indent}{key}={value[0]}"]
                lines.extend(f"{indent}{INDENT}{item}," for item in items)
                lines.append(f"{indent}{value[-1]},")
                return lines
        return [f"{indent}{arg},"]

    def subscript(self, head: str, callee: str, items: Sequence[str]) -> list[str]:
        line = f"{head}{callee}[{', '.join(items)}]"
        if len(line) <= self.line_length or len(items) < 2:
            return [line]
        return [f"{head}{callee}[", *(f"{INDENT}{item}," for item in items), "]"]


_CLOSING = {"{": "}", "[": "]", "(": ")"}


def _split_top_level(text: str) -> list[str]:
    """``text`` split at commas outside brackets and string literals."""
    items, depth, quote, start, index = [], 0, "", 0, 0
    while index < len(text):
        char = text[index]
        if quote:
            if char == "\\":
                index += 1
            elif char == quote:
                quote = ""
        elif char in "\"'":
            quote = char
        elif char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            items.append(text[start:index].strip())
            start = index + 1
        index += 1
    tail = text[start:].strip()
    if tail:
        items.append(tail)
    return items


def _class_key(spec: QuerySetSpec | ManagerSpec) -> Any:
    """What a generated helper class depends on: specs with the same key share one class."""
    return spec.class_key if isinstance(spec, ManagerSpec) else spec


def _docstring(text: str, indent: str, line_length: int) -> list[str]:
    """The docstring ``text`` as lines; a line longer than ``line_length`` is wrapped at spaces."""
    text = inspect.cleandoc(text).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    width = max(line_length - len(indent) - 6, 20)
    lines: list[str] = []
    for line in text.splitlines():
        line = line.rstrip()
        if len(line) <= width:
            lines.append(line)
            continue
        lead = line[: len(line) - len(line.lstrip())]
        lines += textwrap.wrap(
            line, width, initial_indent="", subsequent_indent=lead, break_long_words=False, break_on_hyphens=False
        )
    if len(lines) == 1:
        return [f'{indent}"""{lines[0]}{" " if lines[0].endswith(chr(34)) else ""}"""']
    body = [f"{indent}{line}" if line else "" for line in lines[1:]]
    return [f'{indent}"""{lines[0]}', *body, f'{indent}"""']


def _pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("_") if part)


class _ModuleRenderer:
    def __init__(self, app: AppSpec, classes: Mapping[str, tuple[str, str]], line_length: int, source: str) -> None:
        self.app = app
        self.classes = classes
        self.source = source
        # Field and relation names are reserved too: inside a class body they shadow a module-level name.
        names = {model.class_name for model in app.models} | {"__all__"}
        names |= {f.name for model in app.models for f in model.fields}
        names |= {r.name for model in app.models for r in model.relations}
        names |= {m.name for model in app.models for m in model.managers}
        self.helpers: list[tuple[QuerySetSpec | ManagerSpec, str]] = []
        for model in app.models:
            for manager in model.managers:
                for spec in (manager.queryset, manager if manager.class_name is not None else None):
                    if spec is not None and not any(_class_key(known) == _class_key(spec) for known, _ in self.helpers):
                        name = str(spec.class_name)
                        while name in names:
                            name += "_"
                        names.add(name)
                        self.helpers.append((spec, name))
        self.imports = _Imports(names, line_length)
        self.writer = _Writer(self.imports, line_length)
        self.reserved = names
        self.aliases: dict[TypeSpec, str] = {}
        self.alias_lines: list[str] = []

    def base(self, model: ModelSpec) -> str:
        if model.base is None:
            return self.imports.name("adorm", "Model")
        module, class_name = self.classes[model.base]
        if module == self.app.label:
            return class_name
        return self.imports.name(f".{module}", class_name)

    def meta(self, model: ModelSpec) -> list[str]:
        args = [self.writer.value(model.label)]
        if model.pk != "id":
            args.append(f"pk={self.writer.value(model.pk)}")
        args.append(f"schema_hash={self.writer.value(model.schema_hash)}")
        if model.orm_names:
            args.append(f"orm_names={self.writer.value(model.orm_names)}")
        if model.concrete_model is not None:
            args.append(f"concrete_model={self.writer.value(model.concrete_model)}")
        if model.delete_models:
            args.append(f"delete_models={self.writer.value(tuple(model.delete_models))}")
        return self.writer.call("_meta = ", self.imports.name("adorm", "ModelMeta"), args, INDENT)

    def literal_alias(self, model: ModelSpec, field: FieldSpec) -> None:
        bare = field.type.with_nullable(False)
        if bare in self.aliases:
            return
        name = f"{model.class_name}{_pascal(field.name)}"
        taken = self.reserved | set(self.aliases.values())
        while name in taken:
            name += "_"
        self.aliases[bare] = name
        values = [self.writer.value(value) for value in bare.values]
        self.alias_lines.extend(self.writer.subscript(f"{name} = ", self.writer.ref("typing.Literal"), values))

    def field(self, model: ModelSpec, field: FieldSpec) -> list[str]:
        spec = field.type.with_nullable(field.nullable or field.db_filled or field.type.nullable)
        default: str | None = None
        kwargs: list[str | _Text] = []
        if field.db_filled:
            default = "None"
        elif field.default_factory is not None:
            kwargs.append(f"default_factory={self.writer.ref(field.default_factory)}")
        elif field.default is not NO_DEFAULT:
            default = self.writer.value(field.default)
        elif field.nullable:
            default = "None"
        if field.alias is not None:
            kwargs.append(f"alias={self.writer.value(field.alias)}")
        if field.description:
            kwargs.append(_Text("description", field.description))
        kwargs.extend(f"{key}={self.writer.value(value)}" for key, value in field.constraints.items())
        annotation = self.writer.type(spec, self.aliases)
        if kwargs:
            args: list[str | _Text] = [f"default={default}"] if default is not None else []
            args += kwargs
            head = f"{field.name}: {annotation} = "
            if spec.values and len(f"{INDENT}{head}Field(") > self.writer.line_length:
                self.literal_alias(model, field)
                return self.field(model, field)
            return self.writer.call(head, self.imports.name("pydantic", "Field"), args, INDENT)
        line = f"{INDENT}{field.name}: {annotation}" + (f" = {default}" if default is not None else "")
        if spec.values and len(line) > self.writer.line_length:
            self.literal_alias(model, field)
            return self.field(model, field)
        return [line]

    def schema_source(self, node: Any) -> str:
        """The source of a tenant relation's schema expression (`adorm.codegen.spec.SchemaSource`)."""
        w = self.writer
        kind = node[0]
        callee = self.imports.name("adorm", kind)
        if kind in ("F", "Value"):
            return f"{callee}({w.value(node[1])})"
        if kind == "Cast":
            length = "" if node[2] is None else f", max_length={w.value(node[2])}"
            return f"{callee}({self.schema_source(node[1])}, str{length})"
        return f"{callee}({', '.join(self.schema_source(argument) for argument in node[1])})"

    def relation(self, relation: RelationSpec) -> list[str]:
        w = self.writer
        if relation.kind == "tenant":
            source = relation.schema_source
            schema = w.value(relation.schema) if source is None else self.schema_source(source)
            args = [
                w.value(relation.target),
                f"column={w.value(relation.column)}",
                f"schema={schema}",
                f"models={w.value(tuple(relation.models))}",
            ]
            if relation.session is not None:
                args.append(f"session={w.value(relation.session)}")
            callee = self.imports.name("adorm", _RELATION_CLASSES[relation.kind])
            return w.call(f"{relation.name} = ", callee, args, INDENT)
        if relation.kind == "generic_foreign_key":
            defaults = relation.ct_field == "content_type" and relation.column == "object_id"
            args = [] if defaults else [w.value(relation.ct_field), w.value(relation.column)]
            if not relation.for_concrete_model:
                args.append("for_concrete_model=False")
            callee = self.imports.name("adorm", _RELATION_CLASSES[relation.kind])
            return w.call(f"{relation.name} = ", callee, args, INDENT)
        args = [w.value(relation.target)]
        if relation.kind == "foreign_key":
            if relation.column != f"{relation.name}_id":
                args.append(f"column={w.value(relation.column)}")
        elif relation.kind == "many_to_many":
            args += [
                f"through={w.value(relation.through)}",
                f"source_column={w.value(relation.source_column)}",
                f"target_column={w.value(relation.target_column)}",
            ]
        else:
            args.append(f"column={w.value(relation.column)}")
        callee = self.imports.name("adorm", _RELATION_CLASSES[relation.kind])
        return w.call(f"{relation.name} = ", callee, args, INDENT)

    def helper_name(self, spec: QuerySetSpec | ManagerSpec) -> str:
        return next(name for known, name in self.helpers if _class_key(known) == _class_key(spec))

    def annotation(self, spec: TypeSpec) -> str:
        """The annotation of a driver method's parameter or return type; a model of this module is quoted."""
        text, quoted = self._annotation(spec)
        return f'"{text}"' if quoted else text

    def _annotation(self, spec: TypeSpec) -> tuple[str, bool]:
        if spec.model:
            classes = {model.label: model.class_name for model in self.app.models}
            if spec.name not in classes:
                return self.writer.ref("typing.Any"), False
            return classes[spec.name] + (" | None" if spec.nullable else ""), True
        if spec.args:
            parts = [self._annotation(arg) for arg in spec.args]
            text = f"{self.writer.ref(spec.name)}[{', '.join(text for text, _ in parts)}]"
            quoted = any(q for _, q in parts)
            return (f"{text} | None" if spec.nullable else text), quoted
        return self.writer.type(spec), False

    def parameter(self, parameter: ParameterSpec) -> str:
        prefix = {"var_positional": "*", "var_keyword": "**"}.get(parameter.kind, "")
        text = f"{prefix}{parameter.name}"
        if parameter.type is not None:
            text += f": {self.annotation(parameter.type)}"
        if parameter.default is not NO_DEFAULT:
            value = self.writer.value(parameter.default)
            text += f" = {value}" if parameter.type is not None else f"={value}"
        return text

    def method(self, method: MethodSpec) -> list[str]:
        decorator = self.imports.name("adorm", "driver_method")
        lines = [f"{INDENT}@{decorator}" + ("(queryset_only=True)" if method.queryset_only else "")]
        params = ["self"]
        kinds = [p.kind for p in method.parameters]
        last_positional = max((i for i, kind in enumerate(kinds) if kind == "positional_only"), default=None)
        first_keyword = kinds.index("keyword_only") if "keyword_only" in kinds else None
        for index, parameter in enumerate(method.parameters):
            if index == first_keyword and "var_positional" not in kinds:
                params.append("*")
            params.append(self.parameter(parameter))
            if index == last_positional:
                params.append("/")
        returns = "" if method.returns is None else f" -> {self.annotation(method.returns)}"
        documented = bool(method.doc and method.doc.strip())
        # ruff writes the body of an undocumented stub, `...`, on the line of the signature
        tail = ":" if documented else ": ..."
        head = f"{INDENT}async def {method.name}("
        line = f"{head}{', '.join(params)}){returns}{tail}"
        if len(line) <= self.writer.line_length:
            lines.append(line)
        else:
            lines.append(head)
            lines += [f"{INDENT}{INDENT}{param}," for param in params]
            lines.append(f"{INDENT}){returns}{tail}")
        if documented:
            lines += _docstring(str(method.doc), INDENT + INDENT, self.writer.line_length)
        return lines

    def helper(self, spec: QuerySetSpec | ManagerSpec, name: str) -> list[str]:
        if spec.base is not None:
            module, _, base_name = spec.base.partition(":")
            base = self.imports.name(module, base_name)
        else:
            base = self.imports.name("adorm", "QuerySet" if isinstance(spec, QuerySetSpec) else "Manager")
        lines = [f"class {name}({base}):"]
        body: list[list[str]] = []
        if isinstance(spec, ManagerSpec) and spec.queryset is not None:
            body.append([f"{INDENT}queryset_class = {self.helper_name(spec.queryset)}"])
        body += [self.method(method) for method in spec.methods]
        if not body:
            return [*lines, f"{INDENT}pass"]
        for index, block in enumerate(body):
            if index:
                lines.append("")
            lines += block
        return lines

    def manager(self, manager: ManagerSpec) -> list[str]:
        args = [] if manager.orm_name is None else [self.writer.value(manager.orm_name)]
        if manager.method_manager is not None and manager.method_manager != manager.orm_name:
            args.append(f"method_manager={self.writer.value(manager.method_manager)}")
        if manager.class_name is not None:
            callee = self.helper_name(manager)
        elif manager.queryset is not None:
            callee = f"{self.helper_name(manager.queryset)}.as_manager"
        else:
            callee = self.imports.name("adorm", "Manager")
        return self.writer.call(f"{manager.name} = ", callee, args, INDENT)

    def model(self, model: ModelSpec) -> list[str]:
        lines = [f"class {model.class_name}({self.base(model)}):"]
        if model.doc:
            lines += _docstring(model.doc, INDENT, self.writer.line_length) + [""]
        lines += self.meta(model)
        for field in model.fields:
            lines += self.field(model, field)
        for relation in model.relations:
            lines += self.relation(relation)
        for manager in model.managers:
            lines += self.manager(manager)
        return lines

    def render(self) -> str:
        helpers = [self.helper(spec, name) for spec, name in self.helpers]
        classes = helpers + [self.model(model) for model in self.app.models]
        exported = [self.writer.value(model.class_name) for model in self.app.models]
        all_lines = self.writer.subscript("__all__ = ", "", exported)
        out = f'{HEADER}\n"""adorm models of the {self.source} app ``{self.app.label}``."""\n\n'
        out += "\n\n".join(self.imports.lines()) + "\n\n"
        if self.alias_lines:
            out += "\n".join(self.alias_lines) + "\n\n"
        out += "\n".join(all_lines) + "\n"
        for lines in classes:
            out += "\n\n" + "\n".join(lines) + "\n"
        return out


def render_module(
    app: AppSpec,
    *,
    classes: Mapping[str, tuple[str, str]] | None = None,
    line_length: int = 88,
    source: str = "Django",
) -> str:
    """The source of the module of ``app``'s models.

    ``classes`` maps a model label to the module (an app label) and class name of its generated class, for the bases
    of classes that derive from a model of another module; ``app``'s own models need not be in it. Lines longer than
    ``line_length`` are split as ruff and black split them. ``source`` names the ORM in the module docstring.
    """
    known = {model.label: (app.label, model.class_name) for model in app.models}
    known.update(classes or {})
    return _ModuleRenderer(app, known, line_length, source).render()


def render_package(apps: Sequence[AppSpec], *, line_length: int = 88) -> str:
    """The source of the package ``__init__.py``: it imports every app module, so that every model registers, and
    lists every model class in ``MODELS``."""
    imports = _Imports({"MODELS", *(app.label for app in apps)}, line_length)
    model_name = imports.name("adorm", "Model")
    labels = sorted(app.label for app in apps)
    module_import = f"from . import {', '.join(labels)}" if labels else ""
    if len(module_import) > line_length:
        module_import = "from . import (\n" + "".join(f"{INDENT}{label},\n" for label in labels) + ")"
    items = [f"{app.label}.{model.class_name}" for app in apps for model in app.models]
    head = f"MODELS: tuple[type[{model_name}], ...] = "
    line = head + "(" + ", ".join(items) + ("," if len(items) == 1 else "") + ")"
    if len(line) > line_length:
        line = head + "(\n" + "".join(f"{INDENT}{item},\n" for item in items) + ")"
    sections = imports.lines() + ([module_import] if module_import else [])
    return (
        f"{HEADER}\n"
        '"""Generated adorm models; importing the package registers them."""\n\n'
        + "\n\n".join(sections)
        + "\n\n"
        + line
        + '\n"""Every generated model class."""\n'
    )
